def _env_int(name: str, default: str) -> int:
    raw = os.getenv(name, "").strip() or default
    return int(raw)

def _env_bool(name: str, default: bool) -> bool:
    raw = os.getenv(name, "").strip().lower()
    if not raw:
        return default
    return raw not in ("0", "false", "no", "off")

